def fetch_table_df(table_name: str, db_path: Path) -> pd.DataFrame:
    """Fetch an entire table as a Pandas DataFrame."""
    conn = get_connection(db_path)
    try:
        return pd.read_sql_query(f"SELECT * FROM {table_name}", conn)
    finally:
        conn.close()

def fetch_edges_df(edge_table: str, db_path: Path) -> pd.DataFrame:
    """Fetch a graph edge table as a Pandas DataFrame."""
    conn = get_connection(db_path)
    try:
        return pd.read_sql_query(f"SELECT * FROM {edge_table}", conn)
    finally:
        conn.close()

def clear_graph_edges(db_path: Path):
    """Truncate the predicted edge tables before a new matching run."""
    conn = get_connection(db_path)
    try:
        ensure_matching_stage_column(conn, TABLE_ERP_GW_PRED)
        ensure_matching_stage_column(conn, TABLE_GW_BANK_PRED)

        cursor = conn.cursor()
        cursor.execute("DELETE FROM erp_gw_pred;")
        cursor.execute("DELETE FROM sqlite_sequence WHERE name = 'erp_gw_pred';")
        cursor.execute("DELETE FROM gw_bank_pred;")
        cursor.execute("DELETE FROM sqlite_sequence WHERE name = 'gw_bank_pred';")
        conn.commit()
    finally:
        conn.close()


def save_graph_edges(erp_gw_edges: list, gw_bank_edges: list, db_path: Path):
    """Insert newly computed graph edges into the predicted result tables."""
    if not erp_gw_edges and not gw_bank_edges:
        return

    conn = get_connection(db_path)
    try:
        ensure_matching_stage_column(conn, TABLE_ERP_GW_PRED)
        ensure_matching_stage_column(conn, TABLE_GW_BANK_PRED)

        cursor = conn.cursor()
        cursor.execute("PRAGMA synchronous = NORMAL;")
        cursor.execute("PRAGMA journal_mode = WAL;")

        if erp_gw_edges:
            erp_params = [
                (
                    e["erp_order_id"], e["gateway_payment_id"],
                    float(e["allocated_amount"]), e["match_type"],
                    e.get("matching_stage", "Unknown"),
                    float(e["confidence_score"]), e.get("notes", "")
                )
                for e in erp_gw_edges
            ]
            cursor.executemany("""
                INSERT INTO erp_gw_pred
                (erp_order_id, gateway_payment_id, allocated_amount, match_type, matching_stage, confidence_score, notes)
                VALUES (?, ?, ?, ?, ?, ?, ?)
            """, erp_params)

        if gw_bank_edges:
            gw_params = [
                (
                    e["gateway_payment_id"], e["bank_entry_id"],
                    float(e["allocated_amount"]), e["match_type"],
                    e.get("matching_stage", "Unknown"),
                    float(e["confidence_score"]), e.get("notes", "")
                )
                for e in gw_bank_edges
            ]
            cursor.executemany("""
                INSERT INTO gw_bank_pred
                (gateway_payment_id, bank_entry_id, allocated_amount, match_type, matching_stage, confidence_score, notes)
                VALUES (?, ?, ?, ?, ?, ?, ?)
            """, gw_params)

        conn.commit()
    finally:
        conn.close()

